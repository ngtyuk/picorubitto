#!/usr/bin/env ruby
# frozen_string_literal: true

require 'fileutils'
require 'json'
require 'optparse'

root = File.expand_path('../..', __dir__)
output = File.join(root, 'build', 'studio-site')
marker = File.join(output, '.studio-site-generated')
sample_dirs = []
OptionParser.new do |opts|
  opts.on('--sample ID,TITLE,PATH', 'include a game checkout as a Studio sample') do |value|
    id, title, path = value.split(',', 3)
    abort 'Sample must be ID,TITLE,PATH with a lowercase ID' unless id&.match?(/\A[a-z0-9-]+\z/) && title && !title.empty? && path && !path.empty?
    sample_dirs << [id, title, File.expand_path(path)]
  end
end.parse!
abort 'Duplicate sample ID' unless sample_dirs.map(&:first).uniq.length == sample_dirs.length
samples = sample_dirs.map do |id, title, path|
  abort "Missing sample source: #{path}/main.rb" unless File.file?(File.join(path, 'main.rb'))
  asset_dir = File.join(path, 'assets')
  assets = Dir.exist?(asset_dir) ? Dir.children(asset_dir).sort : []
  assets.each do |name|
    abort "Unsupported sample asset: #{name}" unless name.match?(/\A[A-Za-z0-9][A-Za-z0-9._-]*\z/) && !name.include?('..') && name.match?(/\.(raw|wav|pbf)\z/i) && File.file?(File.join(asset_dir, name))
  end
  { 'id' => id, 'title' => title, 'assets' => assets, 'path' => path }
end

files = %w[
  studio/index.html studio/runner.html studio/studio.css studio/pixel-editor.css
  studio/runner.css studio/studio.rb studio/pixel-editor.rb studio/runner.rb
  studio/studio-bridge.js studio/runner-bridge.js studio/compiler-worker.js
  studio/pixel-art-model.js studio/pixel-editor.js
  studio/vendor/prism/LICENSE studio/vendor/prism/prism-core.min.js
  studio/vendor/prism/prism-clike.min.js studio/vendor/prism/prism-ruby.min.js
  studio/runtime/mrbc.js studio/runtime/mrbc.wasm studio/runtime/version.json
  web/boot.js web/components.rb web/start.rb web/ruby-mark.svg
  emulator/emulator.js emulator/game_adapter.rb emulator/system-screen.js
  emulator/emulator.css emulator/theme.css
  emulator/picoruby/init.iife.js emulator/picoruby/picoruby.js
  emulator/picoruby/picoruby.wasm emulator/picoruby/version.json
  tools/fonts/MARUMINYA-OFL.txt LICENSE
]
files.each { |file| abort "Missing #{file}; run the Studio build first" unless File.file?(File.join(root, file)) }
compiler_version = JSON.parse(File.read(File.join(root, 'studio/runtime/version.json')))
runtime_version = JSON.parse(File.read(File.join(root, 'emulator/picoruby/version.json')))
abort 'Compiler and emulator versions differ; rebuild Studio' unless compiler_version == runtime_version

if File.exist?(output)
  abort "Refusing to replace #{output}: missing generated-directory marker" unless File.file?(marker)
  FileUtils.rm_rf(output)
end
FileUtils.mkdir_p(output)
File.write(marker, "Generated by tools/build/package_studio.rb\n")
files.each do |file|
  destination = File.join(output, file)
  FileUtils.mkdir_p(File.dirname(destination))
  FileUtils.cp(File.join(root, file), destination)
end
sample_root = File.join(output, 'studio/samples')
FileUtils.mkdir_p(sample_root)
samples.each do |sample|
  destination = File.join(sample_root, sample['id'])
  FileUtils.mkdir_p(File.join(destination, 'assets'))
  FileUtils.cp(File.join(sample['path'], 'main.rb'), File.join(destination, 'main.rb'))
  sample['assets'].each { |name| FileUtils.cp(File.join(sample['path'], 'assets', name), File.join(destination, 'assets', name)) }
end
File.write(File.join(sample_root, 'manifest.json'), JSON.generate(samples.map { |sample| sample.reject { |key, _| key == 'path' } }))
# The local-only game selector and Markdown hardware guide are not part of the
# standalone deployment; hide their links while preserving the local Studio.
index = File.join(output, 'studio/index.html')
html = File.read(index).sub('</head>', "  <style>.footer { display: none; }</style>\n  </head>")
File.write(index, html)
File.write(File.join(output, '_redirects'), "/ /studio/ 302\n/emulator/ /studio/ 302\n")
File.write(File.join(output, '_headers'), "/*\n  Cache-Control: no-cache\n")
puts "Studio site: #{output}"
